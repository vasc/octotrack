/**
 * Builds Octotrack as one binary: the CLI, the server, the dashboard and the Claude wake adapter, so that the CLI and
 * the server always come from the same build. Usage: bun scripts/build-binary.ts [out], default build/octo.
 *
 * The build id is a hash of the sources and the built dashboard, so the same code always gets the same id and a CLI can
 * tell when the server it reached is from another build.
 */
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";

const root = join(import.meta.dir, "..");
const dist = join(root, "packages", "web", "dist");
const work = join(root, "build");

function filesUnder(dir: string): string[] {
  return readdirSync(dir)
    .flatMap((name) => {
      const path = join(dir, name);
      return statSync(path).isDirectory() ? filesUnder(path) : [path];
    })
    .sort();
}

function run(command: readonly string[]): void {
  const result = Bun.spawnSync([...command], { cwd: root, stdout: "inherit", stderr: "inherit" });
  if (result.exitCode !== 0) throw new Error(`${command.join(" ")} failed with ${result.exitCode}`);
}

/** Builds the dashboard and the binary, and returns the build id the binary reports. */
export function buildBinary(out: string = join(root, "build", "octo")): { binary: string; buildId: string } {
  run([process.execPath, "run", "--cwd", "packages/web", "build"]);

  const sources = ["core", "server", "cli"].flatMap((name) =>
    filesUnder(join(root, "packages", name, "src")),
  );
  const assets = filesUnder(dist);
  const hasher = new Bun.CryptoHasher("sha256");
  for (const file of [...sources, ...assets]) {
    hasher.update(relative(root, file));
    hasher.update(readFileSync(file));
  }
  const buildId = hasher.digest("hex").slice(0, 12);

  mkdirSync(work, { recursive: true });
  const entry = join(work, "entry.ts");
  const imports = assets.map(
    (file, index) =>
      `import asset${index} from ${JSON.stringify(relative(work, file))} with { type: "file" };`,
  );
  const table = assets.map(
    (file, index) => `  [${JSON.stringify(`/${relative(dist, file)}`)}, asset${index}],`,
  );
  writeFileSync(
    entry,
    [
      "// Generated by scripts/build-binary.ts. The binary's entry: hands over the dashboard, then runs the CLI.",
      ...imports,
      'import { embedDashboard } from "../packages/server/src/dashboard.ts";',
      'import { main } from "../packages/cli/src/main.ts";',
      "embedDashboard(new Map<string, string>([",
      ...table,
      "]));",
      "process.exit(await main(process.argv.slice(2)));",
      "",
    ].join("\n"),
  );

  mkdirSync(dirname(out), { recursive: true });
  run([
    process.execPath,
    "build",
    "--compile",
    entry,
    "--outfile",
    out,
    "--define",
    `process.env.OCTO_BUILD_ID=${JSON.stringify(buildId)}`,
  ]);
  console.log(`Built ${out}, build ${buildId}, with ${assets.length} dashboard files.`);
  return { binary: out, buildId };
}

if (import.meta.main) buildBinary(process.argv[2]);
